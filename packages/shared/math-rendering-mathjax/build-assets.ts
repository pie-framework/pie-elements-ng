/**
 * Writes `dist/assets`, the `./assets` export: the files the browser build loads, MathJax's web
 * fonts and the speech worker with its rule files, copied to `npm/<package>@<version>/<path>` with
 * each package's LICENSE, and `index.js`, whose `assetUrls` gives each file a literal
 * `new URL('./npm/…', import.meta.url)` by npm path. A host's bundler emits the files it names.
 *
 * Runs as the last step of the package's `build` script: `bun build-assets.ts`. The packages and
 * their versions are the manifest's `pie.assetPackages`; the build fails on one `LOADED` does not
 * map, one installed at another version, and a file the package does not ship.
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';

/** What the browser build loads of each asset package: a file, or every file of a `dir/`. */
const LOADED: Record<string, string[]> = {
  mathjax: ['sre/speech-worker.js', 'sre/mathmaps/'],
  '@mathjax/mathjax-newcm-font': ['chtml/woff2/'],
  '@mathjax/mathjax-mhchem-font-extension': ['chtml/woff2/'],
};

export interface AssetFile {
  /** `<package>@<version>/<path>`. */
  npmPath: string;
  /** The installed file. */
  source: string;
}

const DECLARATION = `/**
 * The URL of each file the browser build loads, MathJax's web fonts and the speech worker with its
 * rule files, by npm path: \`<package>@<version>/<path>\`. Pass it as \`math: { assetUrls }\`; each
 * URL is a \`new URL('./npm/…', import.meta.url)\` that the host's bundler emits. The keys carry the
 * MathJax version, so this package must be the version the elements depend on.
 */
export declare const assetUrls: Readonly<Record<string, string>>;
`;

/** The asset files the browser build loads, sorted by npm path, and each package's LICENSE. */
export function assetFiles(packageDir: string): { files: AssetFile[]; licenses: AssetFile[] } {
  const manifest = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8'));
  const packages: Record<string, string> = manifest.pie?.assetPackages ?? {};
  if (Object.keys(packages).length === 0) {
    throw new Error(`${manifest.name} lists no pie.assetPackages`);
  }
  const require = createRequire(join(packageDir, 'package.json'));
  const files: AssetFile[] = [];
  const licenses: AssetFile[] = [];
  for (const [name, version] of Object.entries(packages)) {
    const loaded = LOADED[name];
    if (!loaded) throw new Error(`build-assets.ts does not map ${name}, a pie.assetPackages entry`);
    const dir = realpathSync(dirname(require.resolve(`${name}/package.json`)));
    const installed = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).version;
    if (installed !== version) {
      throw new Error(`${name} is installed at ${installed}; pie.assetPackages lists ${version}`);
    }
    const file = (path: string) => ({
      npmPath: `${name}@${version}/${path}`,
      source: join(dir, path),
    });
    for (const path of loaded) {
      if (!existsSync(join(dir, path))) throw new Error(`${name}@${version} has no ${path}`);
      if (!path.endsWith('/')) {
        files.push(file(path));
        continue;
      }
      const entries = readdirSync(join(dir, path)).filter((entry) =>
        statSync(join(dir, path, entry)).isFile()
      );
      if (entries.length === 0) throw new Error(`${name}@${version} has no files in ${path}`);
      files.push(...entries.map((entry) => file(`${path}${entry}`)));
    }
    if (existsSync(join(dir, 'LICENSE'))) licenses.push(file('LICENSE'));
  }
  files.sort((a, b) => (a.npmPath < b.npmPath ? -1 : 1));
  return { files, licenses };
}

/** `index.js`: `assetUrls`, one literal `new URL` per npm path, which bundlers emit. */
export function assetUrlsModule(npmPaths: string[]): string {
  const entries = npmPaths.map(
    (path) =>
      `  ${JSON.stringify(path)}: new URL(${JSON.stringify(`./npm/${path}`)}, import.meta.url).href,`
  );
  return [
    '// Generated by build-assets.ts: the files the browser build loads, by npm path.',
    'export const assetUrls = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

/** Copies the asset files and licenses to `outDir/npm` and writes `index.js` and `index.d.ts`. */
export function writeAssets(
  packageDir: string,
  outDir = join(packageDir, 'dist/assets')
): AssetFile[] {
  const { files, licenses } = assetFiles(packageDir);
  rmSync(outDir, { recursive: true, force: true });
  for (const { npmPath, source } of [...files, ...licenses]) {
    const target = join(outDir, 'npm', npmPath);
    mkdirSync(dirname(target), { recursive: true });
    copyFileSync(source, target);
  }
  writeFileSync(join(outDir, 'index.js'), assetUrlsModule(files.map((file) => file.npmPath)));
  writeFileSync(join(outDir, 'index.d.ts'), DECLARATION);
  return files;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeAssets(process.cwd());
}
